export function getLanguage() {
  const saved = localStorage.getItem("n-ai-language");
  return saved && translations[saved] ? saved : "mg";
}

export function setLanguage(language) {
  if (!translations[language]) return;
  localStorage.setItem("n-ai-language", language);
  window.dispatchEvent(new CustomEvent("n-ai-language-change", { detail: language }));
}

export function useTranslation() {
  const [language, setCurrentLanguage] = useState(getLanguage());

  useEffect(() => {
    const handler = (event) => setCurrentLanguage(event.detail || getLanguage());
    window.addEventListener("n-ai-language-change", handler);
    return () => window.removeEventListener("n-ai-language-change", handler);
  }, []);

  const t = (key) => translations[language]?.[key] ?? translations.fr[key] ?? key;
  return { language, t, setLanguage };
}
